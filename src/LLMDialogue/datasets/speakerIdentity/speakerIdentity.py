_DSET_NAME = "speakerIdentity"


class SpeakerIdentityDatasetConfig(DatasetConfig):
    def __init__(
        self,
        **kwargs,
    ):
        assert "data_dir" in kwargs and os.path.isdir(
            kwargs["data_dir"]
        ), f"Valid data directory must be specified for this dataset"
        # assert kwargs["variant"] in _VARIANTS, f"Variant must be one of: {_VARIANTS}"
        config_kwargs = {
            "dset_name": _DSET_NAME,
        }
        # Remove a key if it exists in kwargs.
        config_keys = list(config_kwargs.keys())
        for k in config_keys:
            if k in kwargs:
                del config_kwargs[k]
        # Initialize the superclass.
        super().__init__(**kwargs, **config_kwargs)


class SpeakerIdentityDataset(DatasetBuilder):

    def __init__(self, config: Optional[SpeakerIdentityDatasetConfig]):
        super().__init__(config)
        # Attrs.
        # Generate the dataset or load from disk.
        try:
            if self.config.force_regenerate:
                raise Exception()
            self._load_from_disk()
        except Exception as e:
            self._generate()
        # The config and data must not be None.
        # NOTE: self.data contains the data that is core to the dataset being
        # generated by this class.
        assert self.data is not None
        # NOTE: Config defines how the dataset should be generated.
        assert self.config is not None

    def info(self) -> DatasetInfo:
        return DatasetInfo(data=deepcopy(self.data), configs=self.config.to_dict())

    def save_to_disk(self) -> None:
        assert os.path.isdir(self.config.archive_dir)
        config = deepcopy(self.config)
        super()._save_to_disk(config, self.data)

    def __str__(self) -> str:
        return self.config.__str__()

    ###########
    # REQUIRED PRIVATE METHODS
    ###########

    def _load_from_disk(self) -> None:
        # Load the configs and the actual data form the data file and the
        # info files.
        self.config, self.data = super()._load_from_disk(
            self.config.cache_dir, SpeakerIdentityDataset
        )

    def _generate(self) -> None:
        # Save the data attribute
        self.data = self._create_data()
        # Save the dataset to disk.
        self.save_to_disk()

    ###########
    # DSET SPECIFIC PRIVATE METHODS
    ###########

    def _create_data(self) -> Any:
        return {}
